    /**
     * Read/write state for the page: the namespace descriptor, its revision, and
     * the enabled map the Host half derives from Config.
     * @param {any} ctx - the browser plugin context.
     */
    function createController(ctx) {
      let snapshot = {
        status: 'loading',
        ns: ENTRY_ID,
        revision: 0,
        tray: true,
        features: {},
        error: '',
        pending: '',
      };
      const listeners = new Set();
      const publish = (patch) => {
        snapshot = { ...snapshot, ...patch };
        for (const listener of listeners) listener(snapshot);
      };

      const readValues = (descriptor) => {
        const value = descriptor?.value ?? {};
        const features = value.features !== null && typeof value.features === 'object' ? value.features : {};
        return { tray: value.tray !== false, features };
      };

      /** Re-read the namespace; also refreshes the revision the next write must carry. */
      async function load() {
        let response;
        try {
          response = await ctx.remote.settings.describe();
        } catch (error) {
          publish({ status: 'unavailable', error: String(error?.message ?? error) });
          return;
        }
        if (response === undefined || response.ok !== true) {
          publish({ status: 'unavailable', error: '' });
          return;
        }
        const descriptor = pickDescriptor(response.value);
        if (descriptor === undefined) {
          publish({ status: 'unavailableEntry', error: '' });
          return;
        }
        publish({
          status: 'ready',
          ns: descriptor.ns,
          revision: descriptor.revision,
          error: '',
          ...readValues(descriptor),
        });
      }

      /**
       * Write one field of the Config and adopt whatever the Host returns.
       * @param {Record<string, unknown>} patch - Config fields to merge.
       */
      async function write(patch) {
        if (snapshot.status !== 'ready') return;
        try {
          const response = await ctx.remote.settings.update(snapshot.ns, patch, snapshot.revision);
          if (response === undefined || response.ok !== true) publish({ error: 'saveFailed', pending: '' });
        } catch (error) {
          publish({ error: 'saveFailed', pending: '' });
          console.error('dsh-pro-tools: settings write failed', error);
        }
        await load();
        publish({ pending: '' });
      }

      async function setFeature(id, enabled) {
        const features = { ...snapshot.features, [id]: enabled };
        publish({ features, pending: id, error: '' });
        await write({ features });
      }

      async function setTray(enabled) {
        publish({ tray: enabled, pending: 'tray', error: '' });
        await write({ tray: enabled });
      }

      return {
        getSnapshot: () => snapshot,
        subscribe: (listener) => {
          listeners.add(listener);
          return () => {
            listeners.delete(listener);
          };
        },
        load,
        setFeature,
        setTray,
      };
    }

