#!/usr/bin/env node
/**
 * Generate the browser-side feature catalog from `features/*.js`.
 *
 * The settings page cannot import Host modules, so it carries a projected copy
 * of the registry between the `@catalog:begin` / `@catalog:end` markers in
 * `client.js`. Run this after adding or editing a feature; `--check` only
 * verifies that the checked-in copy is current.
 *
 * @module dsh-pro-tools/scripts/build-catalog
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const featuresDir = join(root, 'features');
const clientPath = join(root, 'client.js');
const BEGIN = '    // @catalog:begin (generated by scripts/build-catalog.mjs — do not edit)';
const END = '    // @catalog:end';

/**
 * Load every feature module from disk, skipping the registry itself.
 * @returns {Promise<Array<{ id: string, order: number, defaultEnabled: boolean,
 *   title: { zh: string, en: string }, description: { zh: string, en: string } }>>}
 */
async function readCatalog() {
  const files = readdirSync(featuresDir)
    .filter((name) => name.endsWith('.js') && name !== 'index.js')
    .sort();
  const catalog = [];
  for (const name of files) {
    const module = await import(pathToFileURL(join(featuresDir, name)).href);
    const meta = module.meta;
    if (meta === undefined || typeof meta.id !== 'string') {
      console.warn(`build-catalog: ${name} has no meta.id; skipped`);
      continue;
    }
    const text = (value) => ({
      zh: typeof value?.zh === 'string' ? value.zh : '',
      en: typeof value?.en === 'string' ? value.en : '',
    });
    catalog.push({
      id: meta.id,
      order: Number.isFinite(meta.order) ? meta.order : 100,
      defaultEnabled: meta.defaultEnabled !== false,
      title: text(meta.title),
      description: text(meta.description),
    });
  }
  return catalog.sort((left, right) => left.order - right.order || left.id.localeCompare(right.id));
}

/** Render the block body: one pretty-printed array literal, no line-length games. */
function renderBlock(catalog) {
  if (catalog.length === 0) return `${BEGIN}\n    const FEATURES = [];\n${END}`;
  const lines = catalog.map((feature) => `      ${JSON.stringify(feature)},`);
  return `${BEGIN}\n    const FEATURES = [\n${lines.join('\n')}\n    ];\n${END}`;
}

const catalog = await readCatalog();
const source = readFileSync(clientPath, 'utf8');
const start = source.indexOf(BEGIN);
const end = source.indexOf(END);
if (start < 0 || end < 0) throw new Error('client.js: catalog markers are missing');
const next = `${source.slice(0, start)}${renderBlock(catalog)}${source.slice(end + END.length)}`;
const changed = next !== source;

if (process.argv.includes('--check')) {
  if (changed) {
    console.error('client.js: generated feature catalog is stale — run node scripts/build-catalog.mjs');
    process.exitCode = 1;
  } else {
    console.log(`catalog: up to date (${String(catalog.length)} feature(s))`);
  }
} else {
  writeFileSync(clientPath, next, 'utf8');
  console.log(`catalog: wrote ${String(catalog.length)} feature(s)${changed ? '' : ' (unchanged)'}`);
}
